function paths(obj, prefix = '') {
  return Object.entries(obj).flatMap(([k, v]) =>
    v && typeof v === 'object'
      ? paths(v, prefix ? `${prefix}.${k}` : k)
      : [prefix ? `${prefix}.${k}` : k],
  )
}

const en = paths(PAPERS.en).sort()
for (const locale of ['hi', 'gu']) {
  const other = paths(PAPERS[locale]).sort()
  const missing = en.filter((p) => !other.includes(p))
  const extra = other.filter((p) => !en.includes(p))
  if (missing.length || extra.length) {
    console.error(`\n  ${locale}: missing ${missing.join(', ') || 'none'}`)
    console.error(`  ${locale}: extra   ${extra.join(', ') || 'none'}`)
    process.exit(1)
  }
}
console.log(`\n  ${en.length} keys, identical in all three locales.`)
